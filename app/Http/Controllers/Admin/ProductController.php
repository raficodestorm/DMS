    /**
     * Store a newly created resource in storage.
     */
    public function store(Request $request, BarcodeService $barcodeService)
    {
        $validated = $request->validate([
            'name'              => 'required|string|max:100',
            'sku'               => 'required|string|max:200|unique:products,sku',
            'barcode'           => 'nullable|string|max:100|unique:products,barcode',
            'category_id'       => 'nullable|exists:categories,id',
            'supplier_id'       => 'required|exists:suppliers,id',
            'price'             => 'required|numeric|min:0',
            'stock_alert'       => 'required|integer|min:0',
            'weight'            => 'nullable|numeric|min:0',
            'length'            => 'nullable|numeric|min:0',
            'height'            => 'nullable|numeric|min:0',
            'width'             => 'nullable|numeric|min:0',
            'short_description' => 'nullable|string|max:500',
            'long_description'  => 'nullable|string',
            'is_featured'       => 'nullable|boolean',
            'image'             => 'nullable|image|max:2048',
            'gallery.*'         => 'nullable|image|max:2048',
        ]);

        $barcode = $barcodeService->sanitize($request->barcode);
        $validated['barcode']     = $barcode ?: $barcodeService->generateUniqueBarcode();
        $validated['is_featured'] = $request->boolean('is_featured');
        $validated['purchase_price'] = 0; // Set to 0 by default; updated later via edit

        // Main thumbnail
        if ($request->hasFile('image')) {
            $validated['image'] = $this->uploadFile($request->file('image'), 'products');
        }

        $product = Product::create($validated);

        // Gallery images
        if ($request->hasFile('gallery')) {
            foreach ($request->file('gallery') as $index => $file) {
                $path = $this->uploadFile($file, 'products/gallery');
                ProductImage::create([
                    'product_id' => $product->id,
                    'image'      => $path,
                    'sort_order' => $index,
                    'is_active'  => true,
                ]);
            }
        }

        return redirect()->route('admin.products.show', $product)->with('success', 'Product added successfully!');
    }

